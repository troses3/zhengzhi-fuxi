def build_complete_chaoge():
    final_entries = []
    
    for idx, (chap, grp, kw, sent) in enumerate(raw_chaoge_data):
        if kw in sent:
            hint = sent.replace(kw, "______", 1)
        else:
            hint = sent

        # Pick curated distractors
        dist_words = curated_map.get(kw, [])
        if len(dist_words) < 3:
            pool = [item[2] for item in raw_chaoge_data if item[2] != kw and item[2] not in dist_words]
            dist_words.extend(pool[:3-len(dist_words)])

        distractor_objs = []
        for dw in dist_words[:3]:
            # find accurate description for dw
            matching_sent = distractor_def_map.get(dw)
            if not matching_sent:
                matching_sent = next((item[3] for item in raw_chaoge_data if item[2] == dw), f"【{dw}】是相关领域的重大论断与核心范畴。")
            
            dhint = matching_sent.replace(dw, "______", 1) if dw in matching_sent else matching_sent
            distractor_objs.append({
                "word": dw,
                "meaning": matching_sent,
                "hint": dhint
            })

        entry = {
            "word": kw,
            "meaning": sent,
            "hint": hint,
            "examples": [sent],
            "group": grp,
            "subcategory": grp,
            "chapter": chap,
            "listNum": 100 + (idx // 10),
            "color": "重点",
            "distractors": distractor_objs
        }
        final_entries.append(entry)

    js_path = os.path.join(OUTPUT_DIR, 'political_theory_chaoge.js')
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write("export const chaogePoliticalTheory = " + json.dumps(final_entries, ensure_ascii=False, indent=2) + ";\n")
    print(f"Successfully generated {len(final_entries)} entries in {js_path}!")

if __name__ == "__main__":
    build_complete_chaoge()
