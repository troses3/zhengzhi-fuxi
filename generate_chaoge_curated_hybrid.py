def build_hybrid_chaoge():
    final_entries = []
    
    for idx, (chap, grp, kw, sent) in enumerate(raw_chaoge_data):
        if kw in sent:
            hint = sent.replace(kw, "______", 1)
        else:
            hint = sent

        # Pick curated distractors for cloze quiz
        dist_words = cloze_distractors_map.get(kw, [])
        if len(dist_words) < 3:
            pool = [item[2] for item in raw_chaoge_data if item[2] != kw and item[2] not in dist_words]
            dist_words.extend(pool[:3-len(dist_words)])

        distractor_objs = []
        for dw in dist_words[:3]:
            distractor_objs.append({
                "word": dw,
                "meaning": f"【{dw}】",
                "hint": f"【{dw}】"
            })

        entry = {
            "word": kw,
            "meaning": sent,
            "hint": hint,
            "examples": [sent],
            "group": grp,
            "subcategory": grp,
            "chapter": chap,
            "listNum": 100 + (idx // 10),
            "color": "重点",
            "distractors": distractor_objs
        }
        final_entries.append(entry)

    js_path = os.path.join(OUTPUT_DIR, 'political_theory_chaoge.js')
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write("// 全量 137 道题（专供：挖空特训 与 速览速记）\n")
        f.write("export const chaogePoliticalTheory = " + json.dumps(final_entries, ensure_ascii=False, indent=2) + ";\n\n")
        f.write("// 精选 25 组公考真题成组高频考点（专供：易混辨析）\n")
        f.write("export const chaogeContrastItems = " + json.dumps(chaoge_contrast_dataset, ensure_ascii=False, indent=2) + ";\n")
        
    print(f"Successfully generated {len(final_entries)} cloze items and {len(chaoge_contrast_dataset)} contrast groups in {js_path}!")

if __name__ == "__main__":
    build_hybrid_chaoge()
