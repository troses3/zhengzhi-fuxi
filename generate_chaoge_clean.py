def build_chaoge_db():
    entries = []
    
    for idx, (chap, grp, kw, sent) in enumerate(raw_chaoge_data):
        # Build hint
        if kw in sent:
            hint = sent.replace(kw, "______", 1)
        else:
            hint = sent
            
        entry = {
            "word": kw,
            "meaning": sent,
            "hint": hint,
            "examples": [sent],
            "group": grp,
            "subcategory": grp,
            "chapter": chap,
            "listNum": 100 + (idx // 10),
            "color": "重点"
        }
        entries.append(entry)

    # Build smart distractors from the pool
    rng = random.Random(42)
    for entry in entries:
        word = entry['word']
        my_group = entry['group']
        my_chap = entry['chapter']
        
        candidates = []
        used_words = {word}
        
        # 1. Prefer same group candidates
        same_group = [e for e in entries if e['group'] == my_group and e['word'] not in used_words]
        rng.shuffle(same_group)
        for cand in same_group:
            if cand['word'] not in used_words:
                candidates.append({'word': cand['word'], 'meaning': cand['meaning'], 'hint': cand['hint']})
                used_words.add(cand['word'])
            if len(candidates) >= 3:
                break
                
        # 2. Prefer same chapter candidates
        if len(candidates) < 3:
            same_chap = [e for e in entries if e['chapter'] == my_chap and e['word'] not in used_words]
            rng.shuffle(same_chap)
            for cand in same_chap:
                if cand['word'] not in used_words:
                    candidates.append({'word': cand['word'], 'meaning': cand['meaning'], 'hint': cand['hint']})
                    used_words.add(cand['word'])
                if len(candidates) >= 3:
                    break
                    
        # 3. Fallback to all entries
        if len(candidates) < 3:
            other = [e for e in entries if e['word'] not in used_words]
            rng.shuffle(other)
            for cand in other:
                if cand['word'] not in used_words:
                    candidates.append({'word': cand['word'], 'meaning': cand['meaning'], 'hint': cand['hint']})
                    used_words.add(cand['word'])
                if len(candidates) >= 3:
                    break
                    
        entry['distractors'] = candidates[:3]

    return entries

